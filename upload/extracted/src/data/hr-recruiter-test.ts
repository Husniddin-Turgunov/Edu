export type HrOption = { text: string; correct?: boolean };

export type HrQuestion = {
  section: string;
  knowledgeKind: "knowledge" | "aspiration";
  type: "single" | "text";
  prompt: string;
  options?: string[];
  /** 0-based index for single */
  correctIndex?: number;
  /** пусто = открытый вопрос, автоматом не балл (только для HR) */
  keywords?: string[];
  weight: number;
};

const letterIndex = (letter: string) =>
  letter.toUpperCase().charCodeAt(0) - "A".charCodeAt(0);

function mc(
  section: string,
  prompt: string,
  options: [string, string, string, string],
  answer: "A" | "B" | "C" | "D",
): HrQuestion {
  return {
    section,
    knowledgeKind: "knowledge",
    type: "single",
    prompt,
    options: [...options],
    correctIndex: letterIndex(answer),
    weight: 1,
  };
}

function open(section: string, prompt: string): HrQuestion {
  return {
    section,
    knowledgeKind: "knowledge",
    type: "text",
    prompt,
    keywords: [],
    weight: 0,
  };
}

